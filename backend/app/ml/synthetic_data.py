"""SYNTHETIC training data generator.

IMPORTANT: No real-world appliance failure dataset is used in this project.
The rows produced here are *simulated* appliances whose risk labels come from a
noisy expert-heuristic function (rule score + interaction effects + random
noise). A model trained on this data learns to approximate those heuristics —
its outputs are NOT validated real-world failure probabilities.
"""
import numpy as np
import pandas as pd

from app.ml.features import FEATURE_NAMES, RISK_CLASSES, ApplianceFeatures, rule_based_analysis

DATASET_LABEL = "SYNTHETIC — generated by app/ml/synthetic_data.py (not real failure data)"


def generate_synthetic_dataset(n_samples: int = 6000, seed: int = 42) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    rows = []
    for _ in range(n_samples):
        lifespan = rng.choice([7, 8, 10, 12])
        age = float(np.clip(rng.gamma(2.2, 2.2), 0, 20))
        usage = int(rng.choice([0, 1, 2, 3], p=[0.2, 0.4, 0.28, 0.12]))
        interval = rng.choice([90, 180, 365, 730])
        days_since = int(np.clip(rng.exponential(interval * 0.9), 0, 2500))
        services_2y = int(rng.poisson(max(0.2, 730 / interval * rng.uniform(0.1, 1.0))))
        breakdowns = int(rng.poisson(0.25 + 0.35 * age / lifespan))
        open_issues = int(rng.choice([0, 0, 0, 1, 1, 2, 3]))
        max_sev = int(rng.integers(1, 5)) if open_issues else 0
        # condition worsens with age (with noise)
        cond = int(np.clip(round(age / lifespan * 2 + rng.normal(0.6, 0.8)), 0, 3))

        f = ApplianceFeatures(
            age_years=round(age, 2),
            lifespan_ratio=round(age / lifespan, 3),
            usage_level=usage,
            days_since_service=days_since,
            service_overdue_ratio=round(days_since / interval, 3),
            services_last_2y=services_2y,
            breakdowns_total=breakdowns,
            open_issues=open_issues,
            max_open_severity=max_sev,
            condition_level=cond,
        )
        health, _ = rule_based_analysis(f)
        # Non-linear interaction effects the rules don't capture + noise
        latent = health
        latent -= 4.0 * (usage >= 2) * (f.service_overdue_ratio > 1.5)
        latent -= 3.0 * (breakdowns >= 2) * (f.lifespan_ratio > 0.8)
        latent += 3.0 * (services_2y >= 3)
        latent += rng.normal(0, 6)

        if latent >= 75:
            label = "Low"
        elif latent >= 55:
            label = "Medium"
        elif latent >= 35:
            label = "High"
        else:
            label = "Critical"
        rows.append({**f.to_dict(), "risk_level": label})

    df = pd.DataFrame(rows, columns=FEATURE_NAMES + ["risk_level"])
    df["risk_level"] = pd.Categorical(df["risk_level"], categories=RISK_CLASSES)
    return df
